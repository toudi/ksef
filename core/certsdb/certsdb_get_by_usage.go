package certsdb

import (
	"context"
	"fmt"
	"ksef/internal/logging"
	"slices"
	"time"

	"github.com/samber/lo"
)

func isPreferred(cert Certificate, preferredCertProfile string) bool {
	return cert.ProfileName == preferredCertProfile || cert.UID == preferredCertProfile || cert.SerialNumber == preferredCertProfile
}

// GetCertificateByUsage selects a ministry-issued certificate, which is global
// (not tied to a NIP): SymmetricKeyEncryption, KsefTokenEncryption.
func (c *CertsDB) GetCertificateByUsage(ctx context.Context, usage CertificateUsage) (*Certificate, error) {
	return c.matchCertificate(ctx, usage, "")
}

// GetCertificateByUsageAndNIP selects a user certificate (per-NIP):
// Authentication, Offline.
func (c *CertsDB) GetCertificateByUsageAndNIP(ctx context.Context, usage CertificateUsage, nip string) (*Certificate, error) {
	return c.matchCertificate(ctx, usage, nip)
}

func (c *CertsDB) matchCertificate(ctx context.Context, usage CertificateUsage, nip string) (*Certificate, error) {
	all, err := c.storage.Certs(ctx)
	if err != nil {
		return nil, err
	}

	candidates := filterCertificates(all, c.env, usage, nip)
	if c.preferredProfile != "" {
		candidates = lo.Filter(candidates, func(cert Certificate, _ int) bool {
			return isPreferred(cert, c.preferredProfile)
		})
	}

	switch len(candidates) {
	case 1:
		logging.CertsDBLogger.Debug(
			"wybrano certyfikat",
			"id", candidates[0].UID,
			"typ", candidates[0].Usage,
			"self-signed", candidates[0].SelfSigned,
			"serial", candidates[0].SerialNumber,
			"podmiot", lo.FromPtr(candidates[0].CN),
		)
		return &candidates[0], nil
	case 0:
		// just to avoid the problem when somebody is trying to authenticate with the
		// trusted profile and therefore they don't have any certificate, but on the other hand
		// they still have to persist the token into keyring
		if usage == CertificateUsageAuthentication {
			return &Certificate{
				UID: "*",
			}, nil
		}
		return nil, ErrCertificateNotFound
	default:
		return nil, fmt.Errorf(
			"%w: usage=%s nip=%s: %s",
			ErrAmbiguousCertificate, usage, nip,
			lo.Map(candidates, func(cert Certificate, _ int) string { return cert.UID }),
		)
	}
}

func filterCertificates(certs []Certificate, env string, usage CertificateUsage, nip string) []Certificate {
	now := time.Now()
	return lo.Filter(certs, func(cert Certificate, _ int) bool {
		if string(cert.Gateway) != env || !slices.Contains(cert.Usage, usage) {
			return false
		}
		if cert.ValidFrom.After(now) || cert.ValidTo.Before(now) {
			logging.CertsDBLogger.Debug("certyfikat poza zakresem ważności", "id", cert.UID)
			return false
		}
		// self-signed certificates do not need to have a NIP. they can - if they're
		// generated by NIP rather than by PESEL
		if nip != "" && !slices.Contains(cert.NIP, nip) && !cert.SelfSigned {
			logging.CertsDBLogger.Debug("certyfikat wystawiony dla innego numeru NIP", "id", cert.UID)
			return false
		}
		if nip != "" && !cert.SelfSigned && cert.SerialNumber == "" {
			logging.CertsDBLogger.Debug("certyfikat jest w trakcie przetwarzania przez MCU", "id", cert.UID)
			return false
		}
		return true
	})
}
